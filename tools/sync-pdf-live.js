#!/usr/bin/env node
/* Playbook PDF — copy of the REAL product's book (2026-10-20, per direction "pdf preview เวอร์ชันใช้จริง … ต้องการให้ใช้ pdf
   ตัวนี้แทนที่" the design team's demo). The app's ดาวน์โหลด Playbook preview shows mockup/playbook-pdf/preview.html in an
   iframe; this tool writes that file from a live-playbook link of the product:

     node tools/sync-pdf-live.js "<https://…/better-trade2026/live-playbook/<token>>"

   The link is per user (a token in the path) — pass it on the command line, never commit it. The page can't be framed
   directly (the server sends X-Frame-Options: DENY, no-store), and it isn't server-rendered HTML: the Next page hands a
   component three text chunks — css, mainScript (the same A4 template as the demo) and initScript (that user's data written
   over the template's demo data) — and the browser builds the 59 sheets. So this rebuilds exactly that as one standalone
   page: <style>css</style> + #root.shell + the template's two data scripts + mainScript + initScript. Asset paths are made
   relative (the product serves them from /mockup/playbook-pdf/, same folder as here); any the folder lacks are downloaded.
   The product's own wrapper (header, "56 หน้า", DEBUG panel, confirm bar) is not copied — the app's overlay is used. */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const URL0 = process.argv[2];
if (!URL0 || !/\/live-playbook\//.test(URL0)) { console.error('usage: node tools/sync-pdf-live.js "<live-playbook url>"'); process.exit(1); }
const OUT = path.join(__dirname, '..', 'mockup', 'playbook-pdf');

(async () => {
  const html = await fetch(URL0.split('#')[0]).then((r) => { if (!r.ok) throw new Error(`${r.status} live-playbook`); return r.text(); });
  // the RSC flight data, as one string
  const flight = [...html.matchAll(/self\.__next_f\.push\(\[1,"((?:[^"\\]|\\.)*)"\]\)/g)].map((m) => JSON.parse('"' + m[1] + '"')).join('');
  const props = /"css":"\$([0-9a-f]+)","mainScript":"\$([0-9a-f]+)","initScript":"\$([0-9a-f]+)"/.exec(flight);
  if (!props) throw new Error('book component not found in the page (css/mainScript/initScript) — has the product page changed?');
  // "<id>:T<hex byte length>,<text>" — the header can sit at the end of one push and the text in the next
  const chunk = (id) => {
    const re = new RegExp('(?:^|[^0-9a-f])' + id + ':T([0-9a-f]+),', 'g'); const m = re.exec(flight);
    if (!m) throw new Error('chunk ' + id + ' not found');
    const start = m.index + m[0].length, len = parseInt(m[1], 16);
    return Buffer.from(flight.slice(start, start + len + 4096), 'utf8').subarray(0, len).toString('utf8');
  };
  const rel = (s) => s.split('/mockup/playbook-pdf/').join('');
  const css = rel(chunk(props[1])), main = rel(chunk(props[2])), init = rel(chunk(props[3]));
  if (!/RESULT/.test(init) || !/function render/.test(main)) throw new Error('unexpected script content');

  // assets the book refers to that this folder doesn't have yet (2026-10-20: assets/cardback.jpg)
  const refs = new Set([...(css + main + init).matchAll(/["'(]((?:assets|js|data)\/[\w.\/-]+\.(?:png|jpe?g|webp|svg|ttf|woff2?|js))/g)].map((m) => m[1]));
  const got = [];
  for (const f of refs) {
    const dest = path.join(OUT, f);
    if (fs.existsSync(dest)) continue;
    for (const base of [URL0, new URL('/mockup/playbook-pdf/', URL0).href]) {
      const r = await fetch(new URL(f, base)); if (!r.ok) continue;
      fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, Buffer.from(await r.arrayBuffer())); got.push(f); break;
    }
  }
  const esc = (s) => s.replace(/<\/script/gi, '<\\/script');
  const page = '<!DOCTYPE html>\n<html lang="th">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">\n' +
    '<title>Playbook PDF · BetterTrade 2026</title>\n<!-- Generated by tools/sync-pdf-live.js from the product\'s live-playbook page — do not edit by hand. -->\n' +
    '<style>\n' + css + '\n</style>\n</head>\n<body>\n<div class="shell" id="root"></div>\n' +
    // the template's own data files load first (as in the demo page); initScript then writes the user's data over them
    '<script src="js/library-data.js"></script>\n<script src="data/app/port/edu.js"></script>\n' +
    '<script>\n' + esc(main) + '\n</script>\n<script>\n' + esc(init) + '\n</script>\n</body>\n</html>\n';
  fs.writeFileSync(path.join(OUT, 'preview.html'), page);
  console.log(`preview.html: ${(page.length / 1024).toFixed(0)} KB (css ${css.length}, template ${main.length}, user data ${init.length})` + (got.length ? ` · downloaded ${got.join(', ')}` : ''));
  execFileSync(process.execPath, [path.join(__dirname, 'sync-pdf-mockup.js'), '--manifest'], { stdio: 'inherit' });
})().catch((e) => { console.error(e.message); process.exit(1); });
